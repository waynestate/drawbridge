<?php

declare(strict_types=1);

namespace Waynestate\Drawbridge\Render;

use Waynestate\Drawbridge\Config\Config;
use Waynestate\Drawbridge\Http\HeaderPolicy;

/**
 * Writes the data file the Lua enforcer inside Apache reads.
 *
 * The rules live in PHP (HeaderPolicy), where they are unit-tested. The Lua
 * script is a few lines of loop that applies this table to every request, so
 * there is one source of truth and no second copy of the rules to drift.
 */
final class LuaPolicyRenderer
{
    public function render(Config $config): string
    {
        $gateway = $config->gateway;
        $policy = HeaderPolicy::fromConfig($gateway);

        $out = [];
        $out[] = '-- Generated by `drawbridge render`. Do not edit.';
        $out[] = 'return {';
        $out[] = '  strip = ' . $this->list($policy->expandedNames()) . ',';
        $out[] = '  assertion_header = ' . $this->string($gateway->assertionHeader) . ',';
        $out[] = '  user_header = ' . $this->string($gateway->userHeader) . ',';
        $out[] = '  attribute_headers = {';

        foreach ($gateway->attributeHeaders as $attribute => $header) {
            $out[] = '    ' . $attribute . ' = ' . $this->string($header) . ',';
        }

        $out[] = '  },';
        // mod_auth_mellon puts "mellon-" in front of the name it is given, so the cookie on the wire is never the bare name.
        $names = [];
        foreach ([$gateway->sessionCookie, '__Host-' . $gateway->sessionCookie] as $name) {
            $names[] = '[' . $this->string($name) . '] = true';
            $names[] = '[' . $this->string('mellon-' . $name) . '] = true';
        }

        $out[] = '  cookies = { ' . implode(', ', $names) . ' },';
        $out[] = '  apps = {';

        foreach ($config->apps as $app) {
            $out[] = '    [' . $this->string($app->host) . '] = { mode = ' . $this->string($app->mode) . ' },';
        }

        $out[] = '  },';
        $out[] = '}';

        return implode("\n", $out) . "\n";
    }

    /**
     * @param  list<string>  $values
     */
    private function list(array $values): string
    {
        return '{ ' . implode(', ', array_map($this->string(...), $values)) . ' }';
    }

    private function string(string $value): string
    {
        return '"' . addcslashes($value, "\\\"\n\r\0") . '"';
    }
}
